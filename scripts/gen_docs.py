def hosting_note(profile: str, provider: str) -> str:
    return PROFILE_HOSTING.get(
        (profile, provider), PROVIDER_HOSTING.get(provider, "See `config/models.yaml`")
    )


# What each tool can reach. Tools are code; the gateway decides who may call them.
TOOL_ACCESS = {
    "search_rfp": "Reads the run's own search index of the RFP; writes nothing",
    "date_calc": "Computes dates; reads and writes nothing",
    "ask_research": "Reads the selected research pack, or sends one question to the"
    " NotebookLM notebook code bound; `discover` records each answer in `research.json`",
    "start_research": "Sends one query, built from the research envelope, to NotebookLM"
    " as a deep research job on a notebook code created; `discover` writes the job to"
    " `research.json`",
}


def _rules_table() -> list[str]:
    """The gateway's rules, from their classes, in the order the gateway applies them."""
    from bidwright.harness.rules import OUTCOMES, RULES

    lines = [
        "",
        "## Gateway rules",
        "",
        "`ToolGateway` applies the rules a call triggers in this order, outside the model. The"
        " first rule a call breaks decides its outcome, and the tool never runs; a call counts"
        " against the agent's cap only when it passes every rule (ADR-032).",
        "",
        "| Rule | Trigger | Check | Outcome |",
        "|---|---|---|---|",
    ]
    for rule in RULES:
        lines.append(
            f"| {rule.name} | {_cell(rule.trigger)} | {_cell(rule.description)}"
            f" | {_cell(OUTCOMES[rule.outcome] + rule.note)} |"
        )
    return lines


def _host_services(config: Any) -> list[str]:
    """The research servers, which run on the host and never in Compose: only `live`
    research starts one, bound to loopback (Iteration 2)."""
    from urllib.parse import urlparse

    from bidwright.config import HttpServer

    rows = []
    for name, server in sorted(config.research.servers.items()):
        if not isinstance(server, HttpServer):
            continue
        package = f"`{server.package}=={server.version}`" if server.package else "Not pinned"
        address = urlparse(server.url).netloc or server.url
        rows.append(
            f"| `{name}` | {package}, started on the host for `live` research | `{address}`"
            " | Host only |"
        )
    return rows


def _gateway_control() -> str:
    from bidwright.harness.rules import RULES

    names = ", ".join(rule.name for rule in RULES)
    return (
        f"Every tool call passes `ToolGateway`'s rules, in this order: {names} (`docs/agents.md`)."
    )


CONTROLS = [
    "Every model response must parse into its Pydantic schema, and code checks every quote"
    " against the RFP before a requirement is accepted.",
    "Per-run limits on requests, tokens and active time, checked before every provider attempt"
    " (`config/limits.yaml`).",
    "Mode `DRAFT_ONLY`: nothing is submitted, and every output is `UNREVIEWED_DRAFT` until a"
    " person signs it off.",
    "Spans and the ledger carry hashes, counts, timings and costs, never prompt or response text.",
]


def _package_name(requirement: str) -> str:
    for stop in "<>=!~[; ":
        requirement = requirement.split(stop)[0]
    return requirement.strip()


def ai_bom_md() -> str:
    import tomllib

    import yaml

    from bidwright.config import load_config
    from bidwright.graph.build import run_prompts

    config = load_config()
    prompts = run_prompts(config)
    lines = [
        "# AI bill of materials",
        "",
        GENERATED.strip(),
        "",
        "Every model, prompt, agent control, tool, service and runtime dependency of the current"
        " tag, generated from the code and configuration. EY's paper on AI use case management"
        " screens the risks of agentic AI with an AI bill of materials that includes agentic"
        " control factors; this is Bidwright's. [`governance.md`](governance.md) explains how it is"
        " used.",
        "",
        "## Models",
        "",
        "| Profile | Role | Provider | Model | Fallback | Where prompts go |",
        "|---|---|---|---|---|---|",
    ]
    for profile, roles in config.models.profiles.items():
        for role, rc in roles.items():
            fallback = f"`{rc.fallback}`" if rc.fallback else "None"
            hosting = hosting_note(profile, rc.provider)
            lines.append(
                f"| `{profile}` | {role} | {rc.provider} | `{rc.model}` | {fallback}"
                f" | {_cell(hosting)} |"
            )

    lines += ["", "## Prompts", "", "| Prompt | Version | Role | Hash |", "|---|---|---|---|"]
    for prompt_id, prompt in sorted(prompts.items()):
        lines.append(
            f"| `{prompt_id}` | {prompt.meta.version} | {prompt.meta.role} | `{prompt.hash[:19]}` |"
        )

    lines += [
        "",
        "## Agentic control factors",
        "",
        "| Agent or function | Kind | Tools it may call | Limits |",
        "|---|---|---|---|",
    ]
    callers: dict[str, list[str]] = {}
    for name, agent in config.agents.agents.items():
        for tool in agent.tools:
            callers.setdefault(tool, []).append(name)
        tools = ", ".join(f"`{t}`" for t in agent.tools) or "None"
        limits = (
            ", ".join(f"{k} {v}" for k, v in agent.limits.model_dump(exclude_unset=True).items())
            or "1 call and 1 repair, fixed in code"
        )
        lines.append(f"| `{name}` | {agent.kind} | {tools} | {_cell(limits)} |")
    lines += ["", "Controls on every run, in code:", ""]
    lines += [f"- {control}" for control in [_gateway_control(), *CONTROLS]]

    lines += ["", "## Tools", "", "| Tool | Access | Called by |", "|---|---|---|"]
    for tool, access in TOOL_ACCESS.items():
        called_by = ", ".join(f"`{c}`" for c in callers.get(tool, [])) or "No agent"
        lines.append(f"| `{tool}` | {access} | {called_by} |")

    compose = yaml.safe_load((ROOT / "compose.yaml").read_text(encoding="utf-8"))
    lines += [
        "",
        "## Services",
        "",
        "| Service | Image | Published ports | Profiles |",
        "|---|---|---|---|",
    ]
    for name, service in compose["services"].items():
        image = "Built from this repository" if "build" in service else f"`{service['image']}`"
        ports = ", ".join(f"`{p}`" for p in service.get("ports", [])) or "None"
        profiles = ", ".join(service.get("profiles", [])) or "default"
        lines.append(f"| `{name}` | {_cell(image)} | {ports} | {profiles} |")
    lines += _host_services(config)

    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    locked = {package["name"]: package["version"] for package in lock["package"]}
    lines += [
        "",
        "## Runtime dependencies",
        "",
        "Direct runtime dependencies, at the versions `uv.lock` pins; CI audits them with"
        " `pip-audit`.",
        "",
        "| Package | Locked version |",
        "|---|---|",
    ]
    for requirement in sorted(pyproject["project"]["dependencies"]):
        name = _package_name(requirement)
        lines.append(f"| `{name}` | {locked.get(name, 'not locked')} |")
    lines.append("")
    return "\n".join(lines)


TARGETS: dict[str, Callable[[], str]] = {
    "docs/agents.md": agents_md,
    "docs/reference/cli.md": cli_md,
    "docs/reference/schemas.md": schemas_md,
    "docs/ai-bom.md": ai_bom_md,
}


@contextlib.contextmanager
def _columns(width: int) -> Generator[None]:
    """argparse wraps help text to COLUMNS; set it for the generation, then restore it."""
    before = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = str(width)
    try:
        yield
    finally:
        if before is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = before


def generate() -> dict[str, str]:
    with _columns(100):
        return {path: build().rstrip("\n") + "\n" for path, build in TARGETS.items()}


def stale_paths(docs: dict[str, str]) -> list[str]:
    """Committed files that are missing or differ from what the code generates."""
    out = []
    for path, text in docs.items():
        target = ROOT / path
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            out.append(path)
    return out


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    docs = generate()
    if "--check" in args:
        stale = stale_paths(docs)
        for path in stale:
            print(f"out of date: {path}; run uv run python scripts/gen_docs.py")
        return 1 if stale else 0
    for path, text in docs.items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))  # run as a script: make the repository's packages importable
    raise SystemExit(main())
