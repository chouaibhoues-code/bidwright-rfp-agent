def _constraints(metadata: list[Any]) -> list[str]:
    out = []
    for item in metadata:
        for name in ("pattern", "max_length", "min_length", "ge", "le", "gt", "lt"):
            value = getattr(item, name, None)
            if value is not None:
                out.append(f"{name.replace('_', ' ')} {value}")
        out += _constraints(list(getattr(item, "metadata", [])))
    return out


def _type_name(annotation: Any) -> str:
    """A readable name for a field's type: `str matching ^SRC-\\d{4}$`, `one of 'a', 'b'`."""
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin is typing.Annotated:
        limits = _constraints(list(args[1:]))
        base = _type_name(args[0])
        return f"{base} ({', '.join(limits)})" if limits else base
    if origin in (typing.Union, types.UnionType):
        parts = [_type_name(a) for a in args if a is not type(None)]
        return " | ".join(parts) + (" | None" if type(None) in args else "")
    if origin is typing.Literal:
        return "one of " + ", ".join(repr(a) for a in args)
    if origin in (list, tuple, dict, set):
        return f"{origin.__name__}[{', '.join(_type_name(a) for a in args)}]"
    if isinstance(annotation, type):
        return annotation.__name__
    return repr(annotation).replace("typing.", "")


def schemas_md() -> str:
    from bidwright import schemas

    lines = [
        "# Output and contract schemas",
        "",
        GENERATED.strip(),
        "",
        "Every Pydantic model in `src/bidwright/schemas.py`, in definition order. Code validates"
        " every model response and every record against these before it reaches state or a file.",
        "",
    ]
    for name, obj in vars(schemas).items():
        is_model = isinstance(obj, type) and issubclass(obj, BaseModel)
        if not is_model or obj.__module__ != schemas.__name__:
            continue
        doc = " ".join((obj.__doc__ or "").split())
        lines += [f"## `{name}`", ""]
        if doc:
            lines += [doc, ""]
        fields: dict[str, FieldInfo] = obj.model_fields
        if not fields:
            lines += ["No fields.", ""]
            continue
        lines += ["| Field | Type | Required | Default | Description |", "|---|---|---|---|---|"]
        for field_name, info in fields.items():
            required = "yes" if info.is_required() else "no"
            default = ""
            if not info.is_required():
                default = _cell(repr(info.get_default(call_default_factory=True)))
            type_name = _type_name(info.annotation)
            limits = _constraints(list(info.metadata))
            if limits:
                type_name += f" ({', '.join(limits)})"
            lines.append(
                f"| `{field_name}` | {_cell(type_name)} | {required} | {default}"
                f" | {_cell(info.description or '')} |"
            )
        lines.append("")
    return "\n".join(lines)


