"""Generate the reference documents that would otherwise drift from the code.

- `docs/agents.md` from `config/agents.yaml`, `config/models.yaml`, the prompts' front matter,
  the tool specs and the LangGraph graph itself;
- `docs/reference/cli.md` from the two command-line parsers;
- `docs/reference/schemas.md` from the Pydantic models in `bidwright.schemas`;
- `docs/ai-bom.md`, the AI bill of materials, from `config/`, the prompts, `compose.yaml`,
  `pyproject.toml` and `uv.lock`.

Run `uv run python scripts/gen_docs.py` to write them, or `--check` to fail when a committed
file differs from what the code would generate, which is what CI does.
"""

import contextlib
import io
import os
import sys
import tempfile
import types
import typing
from collections.abc import Callable, Generator
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.fields import FieldInfo

ROOT = Path(__file__).resolve().parents[1]

GENERATED = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand; run the script. -->\n\n"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def agents_md() -> str:
    from bidwright.config import load_config
    from bidwright.graph.build import Runtime, build_graph, run_prompts
    from bidwright.graph.nodes import RunContext
    from bidwright.harness.budget import RunBudget
    from bidwright.llm.client import LLMClient
    from bidwright.llm.replay import CassetteStore
    from bidwright.retrieval import PassageIndex
    from bidwright.tools import date_tool, search_tool

    config = load_config()
    # The typed configuration the code runs with, not the raw YAML; only the fields the files
    # set are shown.
    agents = {
        name: agent.model_dump(exclude_unset=True) for name, agent in config.agents.agents.items()
    }
    models = {
        profile: {role: rc.model_dump(exclude_unset=True) for role, rc in roles.items()}
        for profile, roles in config.models.profiles.items()
    }
    prompts = run_prompts(config)

    lines = [
        "# Agents and LLM functions",
        "",
        GENERATED.strip(),
        "",
        "What each LLM call in the current tag may do, from `config/agents.yaml`,"
        " `config/models.yaml` and the prompts' front matter. `ToolGateway` enforces the tool"
        " allowlists and limits.",
        "",
        "## Roles",
        "",
        "| Name | Kind | Input | Output | Prompt | Model role | Tools | Limits |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, spec in agents.items():
        limits = ", ".join(f"{k} {v}" for k, v in spec.get("limits", {}).items())
        tools = ", ".join(f"`{t}`" for t in spec.get("tools", [])) or "None"
        lines.append(
            f"| `{name}` | {spec['kind']} | `{spec['input']}` | `{spec['output']}`"
            f" | `{spec['prompt']}` | {spec['model_role']} | {tools} | {_cell(limits)} |"
        )

    lines += [
        "",
        "## Prompts",
        "",
        "| Prompt | Version | Role | Pattern | Schema | Decoding | Last tested |",
        "|---|---|---|---|---|---|---|",
    ]
    for prompt_id, prompt in sorted(prompts.items()):
        meta = prompt.meta
        decoding = "; ".join(
            f"{provider}: " + ", ".join(f"{k} {v}" for k, v in settings.items())
            for provider, settings in prompt.decoding.items()
        )
        lines.append(
            f"| `{prompt_id}` | {meta.version} | {meta.role} | {_cell(meta.pattern)}"
            f" | `{meta.output_schema}` | {_cell(decoding)} | {meta.last_tested or 'never'} |"
        )

    lines += [
        "",
        "## Models by profile and role",
        "",
        "| Profile | Role | Provider | Model | Fallback | Settings |",
        "|---|---|---|---|---|---|",
    ]
    for profile, roles in models.items():
        for role, spec in roles.items():
            settings = ", ".join(
                f"{k} {v}" for k, v in spec.items() if k not in {"provider", "model", "fallback"}
            )
            fallback = f"`{spec['fallback']}`" if spec.get("fallback") else "None"
            lines.append(
                f"| `{profile}` | {role} | {spec['provider']} | `{spec['model']}` | {fallback}"
                f" | {_cell(settings)} |"
            )

    with tempfile.TemporaryDirectory() as tmp:
        index = PassageIndex.build([], Path(tmp) / "search.sqlite")
        tools = [search_tool(index), date_tool()]
        lines += [
            "",
            "## Tools",
            "",
            "| Tool | Description | Arguments |",
            "|---|---|---|",
        ]
        for tool in tools:
            spec = tool.spec
            props = spec.parameters.get("properties", {})
            required = set(spec.parameters.get("required", []))
            args = "; ".join(
                f"`{name}`" + ("" if name in required else " (optional)") for name in props
            )
            lines.append(f"| `{spec.name}` | {_cell(spec.description)} | {args} |")

        cassettes = CassetteStore(Path(tmp) / "c")
        client = LLMClient(config, "free", {}, mode="replay", cassettes=cassettes, run_id="docs")
        ctx = RunContext("docs", client, RunBudget(config.limits.run("dev", "free")), prompts, {})
        rfp = ROOT / "inputs" / "dev" / "dev_rfp.pdf"
        graph = build_graph(Runtime(ctx, config, rfp, Path(tmp)))
        mermaid = graph.get_graph().draw_mermaid().strip()

    lines += [
        "",
        "## Runtime graph",
        "",
        "Drawn from the compiled LangGraph graph. The dotted edge is the `Send` fan-out, one"
        " `extract` worker per batch.",
        "",
        "```mermaid",
        mermaid,
        "```",
        "",
    ]
    return "\n".join(lines)


def _help(main: Callable[[list[str]], Any], argv: list[str]) -> str:
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.suppress(SystemExit):
        main(argv)
    return out.getvalue().rstrip()


def cli_md() -> str:
    from bidwright.cli import main as bidwright_main
    from evals.cli import main as eval_main

    sections = [
        ("bidwright", bidwright_main, [[], ["run"], ["demo"], ["record"]]),
        ("bidwright-eval", eval_main, [[], ["score"], ["hash-gold"]]),
    ]
    lines = ["# Command-line reference", "", GENERATED.strip(), ""]
    for program, main, commands in sections:
        for command in commands:
            title = " ".join([program, *command])
            lines += [f"## `{title}`", "", "```text", _help(main, [*command, "--help"]), "```", ""]
    return "\n".join(lines)


def _constraints(metadata: list[Any]) -> list[str]:
    out = []
    for item in metadata:
        for name in ("pattern", "max_length", "min_length", "ge", "le", "gt", "lt"):
            value = getattr(item, name, None)
            if value is not None:
                out.append(f"{name.replace('_', ' ')} {value}")
        out += _constraints(list(getattr(item, "metadata", [])))
    return out


def _type_name(annotation: Any) -> str:
    """A readable name for a field's type: `str matching ^SRC-\\d{4}$`, `one of 'a', 'b'`."""
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin is typing.Annotated:
        limits = _constraints(list(args[1:]))
        base = _type_name(args[0])
        return f"{base} ({', '.join(limits)})" if limits else base
    if origin in (typing.Union, types.UnionType):
        parts = [_type_name(a) for a in args if a is not type(None)]
        return " | ".join(parts) + (" | None" if type(None) in args else "")
    if origin is typing.Literal:
        return "one of " + ", ".join(repr(a) for a in args)
    if origin in (list, tuple, dict, set):
        return f"{origin.__name__}[{', '.join(_type_name(a) for a in args)}]"
    if isinstance(annotation, type):
        return annotation.__name__
    return repr(annotation).replace("typing.", "")


def schemas_md() -> str:
    from bidwright import schemas

    lines = [
        "# Output and contract schemas",
        "",
        GENERATED.strip(),
        "",
        "Every Pydantic model in `src/bidwright/schemas.py`, in definition order. Code validates"
        " every model response and every record against these before it reaches state or a file.",
        "",
    ]
    for name, obj in vars(schemas).items():
        is_model = isinstance(obj, type) and issubclass(obj, BaseModel)
        if not is_model or obj.__module__ != schemas.__name__:
            continue
        doc = " ".join((obj.__doc__ or "").split())
        lines += [f"## `{name}`", ""]
        if doc:
            lines += [doc, ""]
        fields: dict[str, FieldInfo] = obj.model_fields
        if not fields:
            lines += ["No fields.", ""]
            continue
        lines += ["| Field | Type | Required | Default | Description |", "|---|---|---|---|---|"]
        for field_name, info in fields.items():
            required = "yes" if info.is_required() else "no"
            default = ""
            if not info.is_required():
                default = _cell(repr(info.get_default(call_default_factory=True)))
            type_name = _type_name(info.annotation)
            limits = _constraints(list(info.metadata))
            if limits:
                type_name += f" ({', '.join(limits)})"
            lines.append(
                f"| `{field_name}` | {_cell(type_name)} | {required} | {default}"
                f" | {_cell(info.description or '')} |"
            )
        lines.append("")
    return "\n".join(lines)


# Where each provider runs, and so where the text sent to it goes.
