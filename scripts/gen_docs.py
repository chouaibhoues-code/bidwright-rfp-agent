"""Generate the reference documents that would otherwise drift from the code.

- `docs/agents.md` from `config/agents.yaml`, `config/models.yaml`, the prompts' front matter,
  the tool specs and the LangGraph graph itself;
- `docs/reference/cli.md` from the two command-line parsers;
- `docs/reference/schemas.md` from the Pydantic models in `bidwright.schemas`;
- `docs/ai-bom.md`, the AI bill of materials, from `config/`, the prompts, `compose.yaml`,
  `pyproject.toml` and `uv.lock`.

Run `uv run python scripts/gen_docs.py` to write them, or `--check` to fail when a committed
file differs from what the code would generate, which is what CI does.
"""

import contextlib
import io
import os
import sys
import tempfile
import types
import typing
from collections.abc import Callable, Generator
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.fields import FieldInfo

ROOT = Path(__file__).resolve().parents[1]

GENERATED = "<!-- Generated by scripts/gen_docs.py. Do not edit by hand; run the script. -->\n\n"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def agents_md() -> str:
    from bidwright.config import load_config
    from bidwright.graph.build import Runtime, build_graph, run_prompts
    from bidwright.graph.nodes import RunContext
    from bidwright.harness.budget import RunBudget
    from bidwright.llm.client import LLMClient
    from bidwright.llm.replay import CassetteStore
    from bidwright.retrieval import PassageIndex
    from bidwright.schemas import AskResult, ToolResult
    from bidwright.tools import ask_tool, date_tool, search_tool, start_tool

    config = load_config()
    # The typed configuration the code runs with, not the raw YAML; only the fields the files
    # set are shown.
    agents = {
        name: agent.model_dump(exclude_unset=True) for name, agent in config.agents.agents.items()
    }
    models = {
        profile: {role: rc.model_dump(exclude_unset=True) for role, rc in roles.items()}
        for profile, roles in config.models.profiles.items()
    }
    prompts = run_prompts(config)

    lines = [
        "# Agents and LLM functions",
        "",
        GENERATED.strip(),
        "",
        "What each LLM call in the current tag may do, from `config/agents.yaml`,"
        " `config/models.yaml` and the prompts' front matter. `ToolGateway` enforces the tool"
        " allowlists and limits.",
        "",
        "## Roles",
        "",
        "| Name | Kind | Input | Output | Prompt | Model role | Tools | Limits |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, spec in agents.items():
        limits = ", ".join(f"{k} {v}" for k, v in spec.get("limits", {}).items()) or "None"
        tools = ", ".join(f"`{t}`" for t in spec.get("tools", [])) or "None"
        lines.append(
            f"| `{name}` | {spec['kind']} | `{spec['input']}` | `{spec['output']}`"
            f" | `{spec['prompt']}` | {spec['model_role']} | {tools} | {_cell(limits)} |"
        )
    lines += [
        "",
        "A function declares no limits: it makes one call and one repair, fixed in the node"
        " code, and with the second pass on, `extract` makes one more call per pack, with one"
        " format repair. An agent's limits bound its tool loop.",
    ]

    lines += [
        "",
        "## Prompts",
        "",
        "| Prompt | Version | Role | Pattern | Schema | Decoding | Last tested |",
        "|---|---|---|---|---|---|---|",
    ]
    for prompt_id, prompt in sorted(prompts.items()):
        meta = prompt.meta
        decoding = "; ".join(
            f"{provider}: " + ", ".join(f"{k} {v}" for k, v in settings.items())
            for provider, settings in prompt.decoding.items()
        )
        lines.append(
            f"| `{prompt_id}` | {meta.version} | {meta.role} | {_cell(meta.pattern)}"
            f" | `{meta.output_schema}` | {_cell(decoding)} | {meta.last_tested or 'never'} |"
        )

    lines += [
        "",
        "## Models by profile and role",
        "",
        "| Profile | Role | Provider | Model | Fallback | Settings |",
        "|---|---|---|---|---|---|",
    ]
    for profile, roles in models.items():
        for role, spec in roles.items():
            settings = ", ".join(
                f"{k} {v}" for k, v in spec.items() if k not in {"provider", "model", "fallback"}
            )
            fallback = f"`{spec['fallback']}`" if spec.get("fallback") else "None"
            lines.append(
                f"| `{profile}` | {role} | {spec['provider']} | `{spec['model']}` | {fallback}"
                f" | {_cell(settings)} |"
            )

    class Unasked:
        """A research provider for the tool table, which never asks anything."""

        def ask(self, question: str) -> AskResult:
            return AskResult()

    with tempfile.TemporaryDirectory() as tmp:
        index = PassageIndex.build([], Path(tmp) / "search.sqlite")
        tools = [
            search_tool(index),
            date_tool(),
            ask_tool(Unasked(), max_excerpts=config.research.questions.max_matches),
            start_tool(lambda args: ToolResult(status="EMPTY")),
        ]
        lines += [
            "",
            "## Tools",
            "",
            "| Tool | Description | Arguments |",
            "|---|---|---|",
        ]
        for tool in tools:
            spec = tool.spec
            props = spec.parameters.get("properties", {})
            required = set(spec.parameters.get("required", []))
            args = "; ".join(
                f"`{name}`" + ("" if name in required else " (optional)") for name in props
            )
            lines.append(f"| `{spec.name}` | {_cell(spec.description)} | {args} |")

        lines += _rules_table()

        cassettes = CassetteStore(Path(tmp) / "c")
        client = LLMClient(config, "free", {}, mode="replay", cassettes=cassettes, run_id="docs")
        ctx = RunContext(
            run_id="docs",
            client=client,
            budget=RunBudget(config.limits.run("dev", "free")),
            prompts=prompts,
            passages={},
        )
        rfp = ROOT / "inputs" / "dev" / "dev_rfp.pdf"
        graph = build_graph(Runtime(ctx=ctx, config=config, source=rfp, run_dir=Path(tmp)))
        mermaid = graph.get_graph().draw_mermaid().strip()

    lines += [
        "",
        "## Runtime graph",
        "",
        "Drawn from the compiled LangGraph graph. The dotted edges are conditional: the `Send`"
        " fan-outs, one `extract` worker per pack and one `consolidate` worker per cluster the"
        " model step takes, and the stops that `until` and `--baseline b0` choose.",
        "",
        "```mermaid",
        mermaid,
        "```",
        "",
    ]
    return "\n".join(lines)


def _help(main: Callable[[list[str]], Any], argv: list[str]) -> str:
    out = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.suppress(SystemExit):
        main(argv)
    return out.getvalue().rstrip()


